CREATE TABLE brands (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL,
                        slug VARCHAR(150) NOT NULL UNIQUE,
                        description TEXT,
                        logo_url VARCHAR(500),
                        website_url VARCHAR(500),
                        country VARCHAR(100),
                        is_active BOOLEAN NOT NULL
);

CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL,
                            slug VARCHAR(150) NOT NULL UNIQUE,
                            description TEXT,
                            image_url VARCHAR(500),
                            sort_order INTEGER NOT NULL,
                            is_active BOOLEAN NOT NULL,
                            parent_category_id BIGINT,
                            CONSTRAINT fk_category_parent
                                FOREIGN KEY (parent_category_id) REFERENCES categories(id)
);

CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(200) NOT NULL,
                          slug VARCHAR(250) NOT NULL UNIQUE,
                          description TEXT,
                          short_description VARCHAR(1000),
                          sku VARCHAR(64) NOT NULL UNIQUE,
                          base_price NUMERIC(12,2) NOT NULL,
                          discount_price NUMERIC(12,2),
                          discount_start_date TIMESTAMP(6),
                          discount_end_date TIMESTAMP(6),
                          stock_quantity INTEGER NOT NULL,
                          reserved_quantity INTEGER NOT NULL,
                          low_stock_threshold INTEGER NOT NULL,
                          weight NUMERIC(10,3),
                          dimensions VARCHAR(100),
                          is_active BOOLEAN NOT NULL,
                          is_featured BOOLEAN NOT NULL,
                          is_new_arrival BOOLEAN NOT NULL,
                          average_rating NUMERIC(3,2) NOT NULL,
                          review_count INTEGER NOT NULL,
                          view_count BIGINT NOT NULL,
                          sales_count BIGINT NOT NULL,
                          meta_title VARCHAR(200),
                          meta_description VARCHAR(500),
                          created_at TIMESTAMP(6) NOT NULL,
                          updated_at TIMESTAMP(6) NOT NULL,
                          brand_id BIGINT,
                          category_id BIGINT NOT NULL,
                          CONSTRAINT fk_product_brand
                              FOREIGN KEY (brand_id) REFERENCES brands(id),
                          CONSTRAINT fk_product_category
                              FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE product_variants (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  sku VARCHAR(64) NOT NULL UNIQUE,
                                  name VARCHAR(200) NOT NULL,
                                  attributes JSONB,
                                  price NUMERIC(12,2) NOT NULL,
                                  stock_quantity INTEGER NOT NULL,
                                  reserved_quantity INTEGER NOT NULL,
                                  image_url VARCHAR(500),
                                  is_active BOOLEAN NOT NULL,
                                  product_id BIGINT NOT NULL,
                                  CONSTRAINT fk_variant_product
                                      FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE product_images (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                image_url VARCHAR(500) NOT NULL,
                                thumbnail_url VARCHAR(500),
                                alt_text VARCHAR(200),
                                is_primary BOOLEAN NOT NULL,
                                sort_order INTEGER NOT NULL,
                                product_id BIGINT NOT NULL,
                                CONSTRAINT fk_image_product
                                    FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE product_specifications (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        name VARCHAR(100) NOT NULL,
                                        value VARCHAR(1000) NOT NULL,
                                        group_name VARCHAR(100),
                                        sort_order INTEGER NOT NULL,
                                        product_id BIGINT NOT NULL,
                                        CONSTRAINT fk_specification_product
                                            FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE INDEX idx_brand_name ON brands(name);
CREATE INDEX idx_brand_active ON brands(is_active);

CREATE INDEX idx_category_parent ON categories(parent_category_id);
CREATE INDEX idx_category_sort ON categories(sort_order);
CREATE INDEX idx_category_active ON categories(is_active);

CREATE INDEX idx_product_category ON products(category_id);
CREATE INDEX idx_product_brand ON products(brand_id);
CREATE INDEX idx_product_name ON products(name);
CREATE INDEX idx_product_price ON products(base_price);
CREATE INDEX idx_product_stock ON products(stock_quantity);
CREATE INDEX idx_product_rating ON products(average_rating);
CREATE INDEX idx_product_sales ON products(sales_count);
CREATE INDEX idx_product_created ON products(created_at);
CREATE INDEX idx_product_active ON products(is_active);
CREATE INDEX idx_product_featured ON products(is_featured);
CREATE INDEX idx_product_new_arrival ON products(is_new_arrival);

CREATE INDEX idx_variant_product ON product_variants(product_id);
CREATE INDEX idx_image_product ON product_images(product_id);
CREATE INDEX idx_specification_product ON product_specifications(product_id);