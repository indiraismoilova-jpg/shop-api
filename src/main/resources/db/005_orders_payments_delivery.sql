CREATE TABLE delivery_options (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  name VARCHAR(100) NOT NULL,
                                  code VARCHAR(50) NOT NULL UNIQUE,
                                  description TEXT,
                                  base_price NUMERIC(12,2) NOT NULL,
                                  free_threshold NUMERIC(12,2),
                                  estimated_days_min INTEGER NOT NULL,
                                  estimated_days_max INTEGER NOT NULL,
                                  is_active BOOLEAN NOT NULL,
                                  CONSTRAINT chk_delivery_price
                                      CHECK (base_price >= 0),
                                  CONSTRAINT chk_delivery_threshold
                                      CHECK (free_threshold >= 0),
                                  CONSTRAINT chk_delivery_days
                                      CHECK (
                                          estimated_days_min >= 0
                                              AND estimated_days_max >= estimated_days_min
                                          )
);

CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_number VARCHAR(50) NOT NULL UNIQUE,
                        status VARCHAR(20) NOT NULL,
                        shipping_country VARCHAR(100) NOT NULL,
                        shipping_city VARCHAR(100) NOT NULL,
                        shipping_street VARCHAR(200) NOT NULL,
                        shipping_building VARCHAR(30) NOT NULL,
                        shipping_apartment VARCHAR(30),
                        shipping_postal_code VARCHAR(20),
                        shipping_recipient_name VARCHAR(200) NOT NULL,
                        shipping_recipient_phone VARCHAR(30) NOT NULL,
                        delivery_method VARCHAR(30) NOT NULL,
                        delivery_tracking_number VARCHAR(100),
                        estimated_delivery_date TIMESTAMP(6),
                        actual_delivery_date TIMESTAMP(6),
                        subtotal NUMERIC(12,2) NOT NULL,
                        shipping_cost NUMERIC(12,2) NOT NULL,
                        discount NUMERIC(12,2) NOT NULL,
                        bonus_points_used INTEGER NOT NULL,
                        bonus_points_earned INTEGER NOT NULL,
                        total_amount NUMERIC(12,2) NOT NULL,
                        promo_code VARCHAR(100),
                        customer_note TEXT,
                        admin_note TEXT,
                        created_at TIMESTAMP(6) NOT NULL,
                        updated_at TIMESTAMP(6) NOT NULL,
                        paid_at TIMESTAMP(6),
                        shipped_at TIMESTAMP(6),
                        delivered_at TIMESTAMP(6),
                        user_id BIGINT NOT NULL,
                        CONSTRAINT fk_order_user
                            FOREIGN KEY (user_id) REFERENCES users(id),
                        CONSTRAINT chk_order_amounts
                            CHECK (
                                subtotal >= 0
                                    AND shipping_cost >= 0
                                    AND discount >= 0
                                    AND total_amount >= 0
                                    AND bonus_points_used >= 0
                                    AND bonus_points_earned >= 0
                                )
);

CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             quantity INTEGER NOT NULL,
                             price_at_purchase NUMERIC(12,2) NOT NULL,
                             product_snapshot JSONB NOT NULL,
                             order_id BIGINT NOT NULL,
                             product_id BIGINT NOT NULL,
                             variant_id BIGINT,
                             CONSTRAINT fk_order_item_order
                                 FOREIGN KEY (order_id) REFERENCES orders(id),
                             CONSTRAINT fk_order_item_product
                                 FOREIGN KEY (product_id) REFERENCES products(id),
                             CONSTRAINT fk_order_item_variant
                                 FOREIGN KEY (variant_id) REFERENCES product_variants(id),
                             CONSTRAINT chk_order_item_quantity
                                 CHECK (quantity > 0),
                             CONSTRAINT chk_order_item_price
                                 CHECK (price_at_purchase >= 0)
);

CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          transaction_id VARCHAR(100) UNIQUE,
                          payment_method VARCHAR(30) NOT NULL,
                          status VARCHAR(30) NOT NULL,
                          amount NUMERIC(12,2) NOT NULL,
                          currency VARCHAR(3) NOT NULL,
                          bonus_points_used INTEGER NOT NULL,
                          card_last_four_digits VARCHAR(4),
                          paid_at TIMESTAMP(6),
                          error_message TEXT,
                          error_code VARCHAR(100),
                          refunded_amount NUMERIC(12,2) NOT NULL,
                          metadata JSONB,
                          order_id BIGINT NOT NULL UNIQUE,
                          CONSTRAINT fk_payment_order
                              FOREIGN KEY (order_id) REFERENCES orders(id),
                          CONSTRAINT chk_payment_amounts
                              CHECK (
                                  amount >= 0
                                      AND refunded_amount >= 0
                                      AND refunded_amount <= amount
                                      AND bonus_points_used >= 0
                                  ),
                          CONSTRAINT chk_payment_card_last_four
                              CHECK (card_last_four_digits ~ '^[0-9]{4}$')
    );

CREATE INDEX idx_delivery_active ON delivery_options(is_active);

CREATE INDEX idx_order_user ON orders(user_id);
CREATE INDEX idx_order_status ON orders(status);
CREATE INDEX idx_order_created ON orders(created_at);

CREATE INDEX idx_order_item_order ON order_items(order_id);
CREATE INDEX idx_order_item_product ON order_items(product_id);
CREATE INDEX idx_order_item_variant ON order_items(variant_id);

CREATE INDEX idx_payment_status ON payments(status);
CREATE INDEX idx_payment_paid ON payments(paid_at);