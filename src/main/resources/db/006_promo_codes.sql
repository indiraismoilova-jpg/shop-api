CREATE TABLE promo_codes (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             code VARCHAR(100) NOT NULL UNIQUE,
                             description TEXT,
                             discount_type VARCHAR(30) NOT NULL,
                             discount_value NUMERIC(12,2) NOT NULL,
                             min_order_amount NUMERIC(12,2),
                             max_discount_amount NUMERIC(12,2),
                             max_usage_count INTEGER,
                             current_usage_count INTEGER NOT NULL,
                             max_usage_per_user INTEGER,
                             valid_from TIMESTAMP(6) NOT NULL,
                             valid_to TIMESTAMP(6) NOT NULL,
                             is_active BOOLEAN NOT NULL,
                             created_by_id BIGINT,
                             CONSTRAINT fk_promo_created_by
                                 FOREIGN KEY (created_by_id) REFERENCES users(id),
                             CONSTRAINT chk_promo_dates
                                 CHECK (valid_to > valid_from),
                             CONSTRAINT chk_promo_discount
                                 CHECK (discount_value >= 0),
                             CONSTRAINT chk_promo_min_amount
                                 CHECK (min_order_amount >= 0),
                             CONSTRAINT chk_promo_max_discount
                                 CHECK (max_discount_amount >= 0),
                             CONSTRAINT chk_promo_usage_count
                                 CHECK (current_usage_count >= 0),
                             CONSTRAINT chk_promo_max_usage
                                 CHECK (max_usage_count > 0),
                             CONSTRAINT chk_promo_user_limit
                                 CHECK (max_usage_per_user > 0),
                             CONSTRAINT chk_promo_percentage
                                 CHECK (
                                     discount_type <> 'PERCENTAGE'
                                         OR discount_value <= 100
                                     )
);

CREATE TABLE promo_code_categories (
                                       promo_code_id BIGINT NOT NULL,
                                       category_id BIGINT NOT NULL,
                                       PRIMARY KEY (promo_code_id, category_id),
                                       CONSTRAINT fk_promo_category_promo
                                           FOREIGN KEY (promo_code_id) REFERENCES promo_codes(id),
                                       CONSTRAINT fk_promo_category_category
                                           FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE promo_code_products (
                                     promo_code_id BIGINT NOT NULL,
                                     product_id BIGINT NOT NULL,
                                     PRIMARY KEY (promo_code_id, product_id),
                                     CONSTRAINT fk_promo_product_promo
                                         FOREIGN KEY (promo_code_id) REFERENCES promo_codes(id),
                                     CONSTRAINT fk_promo_product_product
                                         FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE promo_code_usages (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   discount_applied NUMERIC(12,2) NOT NULL,
                                   used_at TIMESTAMP(6) NOT NULL,
                                   promo_code_id BIGINT NOT NULL,
                                   user_id BIGINT NOT NULL,
                                   order_id BIGINT NOT NULL,
                                   CONSTRAINT chk_promo_usage_discount
                                       CHECK (discount_applied >= 0),
                                   CONSTRAINT fk_promo_usage_promo
                                       FOREIGN KEY (promo_code_id) REFERENCES promo_codes(id),
                                   CONSTRAINT fk_promo_usage_user
                                       FOREIGN KEY (user_id) REFERENCES users(id),
                                   CONSTRAINT fk_promo_usage_order
                                       FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE INDEX idx_promo_created_by ON promo_codes(created_by_id);
CREATE INDEX idx_promo_active ON promo_codes(is_active);
CREATE INDEX idx_promo_valid_from ON promo_codes(valid_from);
CREATE INDEX idx_promo_valid_to ON promo_codes(valid_to);

CREATE INDEX idx_promo_category_category
    ON promo_code_categories(category_id);

CREATE INDEX idx_promo_product_product
    ON promo_code_products(product_id);

CREATE INDEX idx_promo_usage_promo ON promo_code_usages(promo_code_id);
CREATE INDEX idx_promo_usage_user ON promo_code_usages(user_id);
CREATE INDEX idx_promo_usage_order ON promo_code_usages(order_id);
CREATE INDEX idx_promo_usage_used ON promo_code_usages(used_at);