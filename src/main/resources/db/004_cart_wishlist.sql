CREATE TABLE carts (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       session_id VARCHAR(100),
                       applied_promo_code VARCHAR(100),
                       created_at TIMESTAMP(6) NOT NULL,
                       updated_at TIMESTAMP(6) NOT NULL,
                       user_id BIGINT,
                       CONSTRAINT fk_cart_user
                           FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE cart_items (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            quantity INTEGER NOT NULL,
                            price_at_add NUMERIC(12,2) NOT NULL,
                            cart_id BIGINT NOT NULL,
                            product_id BIGINT NOT NULL,
                            variant_id BIGINT,
                            CONSTRAINT chk_cart_item_quantity
                                CHECK (quantity > 0),
                            CONSTRAINT chk_cart_item_price
                                CHECK (price_at_add >= 0),
                            CONSTRAINT fk_cart_item_cart
                                FOREIGN KEY (cart_id) REFERENCES carts(id),
                            CONSTRAINT fk_cart_item_product
                                FOREIGN KEY (product_id) REFERENCES products(id),
                            CONSTRAINT fk_cart_item_variant
                                FOREIGN KEY (variant_id) REFERENCES product_variants(id)
);

CREATE TABLE wishlists (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           price_at_add NUMERIC(12,2) NOT NULL,
                           notify_on_price_drop BOOLEAN NOT NULL,
                           notify_on_back_in_stock BOOLEAN NOT NULL,
                           added_at TIMESTAMP(6) NOT NULL,
                           user_id BIGINT NOT NULL,
                           product_id BIGINT NOT NULL,
                           CONSTRAINT uq_wishlist_user_product
                               UNIQUE (user_id, product_id),
                           CONSTRAINT chk_wishlist_price
                               CHECK (price_at_add >= 0),
                           CONSTRAINT fk_wishlist_user
                               FOREIGN KEY (user_id) REFERENCES users(id),
                           CONSTRAINT fk_wishlist_product
                               FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE INDEX idx_cart_user ON carts(user_id);
CREATE INDEX idx_cart_session ON carts(session_id);
CREATE INDEX idx_cart_updated ON carts(updated_at);

CREATE INDEX idx_cart_item_cart ON cart_items(cart_id);
CREATE INDEX idx_cart_item_product ON cart_items(product_id);
CREATE INDEX idx_cart_item_variant ON cart_items(variant_id);

CREATE INDEX idx_wishlist_user ON wishlists(user_id);
CREATE INDEX idx_wishlist_product ON wishlists(product_id);
CREATE INDEX idx_wishlist_added ON wishlists(added_at);